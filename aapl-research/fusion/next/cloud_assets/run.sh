#!/usr/bin/env bash
set -euo pipefail
FUSION_TASK_ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
cd -- "$FUSION_TASK_ROOT"
export PYTHONPATH="$FUSION_TASK_ROOT" PYTHONDONTWRITEBYTECODE=1
export FUSION_EXECUTION_PROFILE=autodl
export OMP_NUM_THREADS=4 OPENBLAS_NUM_THREADS=4 MKL_NUM_THREADS=4 NUMEXPR_NUM_THREADS=4
export TOKENIZERS_PARALLELISM=false CUBLAS_WORKSPACE_CONFIG=:4096:8
export HF_HUB_OFFLINE=1 TRANSFORMERS_OFFLINE=1 HF_HUB_DISABLE_TELEMETRY=1
export FUSION_CHRONOS_WEIGHTS="$FUSION_TASK_ROOT/weights/chronos2"
export HF_HOME="$FUSION_TASK_ROOT/.cache/hf" XDG_CACHE_HOME="$FUSION_TASK_ROOT/.cache"
export TORCH_HOME="$FUSION_TASK_ROOT/.cache/torch" TMPDIR="$FUSION_TASK_ROOT/tmp"
export WANDB_MODE=disabled COMET_MODE=DISABLED
mkdir -p "$TMPDIR" "$HF_HOME" "$TORCH_HOME"
exec "$FUSION_TASK_ROOT/.venv/bin/python" "$@"

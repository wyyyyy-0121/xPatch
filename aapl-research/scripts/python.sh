#!/usr/bin/env bash
set -euo pipefail
AAPL_RESEARCH_ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
export PYTHONDONTWRITEBYTECODE=1
export PYTHONPATH="$AAPL_RESEARCH_ROOT"
AAPL_CPU_THREADS="${AAPL_CPU_THREADS:-4}"
AAPL_CPU_IDS="${AAPL_CPU_IDS:-0-17}"
export AAPL_CPU_THREADS
export OMP_NUM_THREADS="$AAPL_CPU_THREADS" OPENBLAS_NUM_THREADS="$AAPL_CPU_THREADS" MKL_NUM_THREADS="$AAPL_CPU_THREADS" NUMEXPR_NUM_THREADS="$AAPL_CPU_THREADS"
export RAYON_NUM_THREADS="$AAPL_CPU_THREADS" ARROW_NUM_THREADS="$AAPL_CPU_THREADS" POLARS_MAX_THREADS="$AAPL_CPU_THREADS"
export TOKENIZERS_PARALLELISM=false CUBLAS_WORKSPACE_CONFIG=:4096:8
export HF_HUB_OFFLINE=1 TRANSFORMERS_OFFLINE=1 HF_HUB_DISABLE_TELEMETRY=1
export HF_HOME="$AAPL_RESEARCH_ROOT/.cache/hf" TORCH_HOME="$AAPL_RESEARCH_ROOT/.cache/torch"
export XDG_CACHE_HOME="$AAPL_RESEARCH_ROOT/.cache" CUDA_CACHE_PATH="$AAPL_RESEARCH_ROOT/.cache/cuda"
export TRITON_CACHE_DIR="$AAPL_RESEARCH_ROOT/.cache/triton" TMPDIR="$AAPL_RESEARCH_ROOT/tmp"
export WANDB_MODE=disabled COMET_MODE=DISABLED
mkdir -p "$TMPDIR" "$HF_HOME" "$TORCH_HOME" "$CUDA_CACHE_PATH" "$TRITON_CACHE_DIR"
cd -- "$AAPL_RESEARCH_ROOT"
exec taskset -c "$AAPL_CPU_IDS" "$AAPL_RESEARCH_ROOT/.venv/bin/python" "$@"
